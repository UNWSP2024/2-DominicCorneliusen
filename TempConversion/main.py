#Variables/User Input
Degrees_Celsius = float(input("Enter the temperature in ºCelsius: "))
Degrees_Fahrenheit = ((9 / 5) * Degrees_Celsius) + 32

#Print
print(Degrees_Celsius, "ºCelsius is", Degrees_Fahrenheit, "ºFahrenheit")